-- ============================================================
-- Sports Hub (SCMS) - PostgreSQL schema, multi-tenant edition
--
-- Two kinds of tables live here:
--   1. Platform tables (Clubs, ClubUsers, PlatformPlans, SubscriptionRequests,
--      Subscriptions, Users) - shared and NOT tenant scoped.
--   2. Club-owned tables - every one carries ClubID and is protected by
--      row level security (policies are installed by
--      db/migrations/002_multi_tenant.sql, see the note at the bottom).
--
-- Idempotent: safe to run on every boot.
-- ============================================================

-- ================================================================
-- Tenant context helpers
--
-- The HTTP layer runs every query batch inside a transaction and sets
-- these with set_config('app.club_id', ..., true) before the statements
-- execute (see config/db.js). Reading an unset setting returns NULL,
-- which makes the ClubID default and every RLS policy fail closed:
-- a request without a resolved club sees nothing instead of everything.
-- ================================================================
create or replace function current_club()
returns integer
language sql
stable
as $$ select nullif(current_setting('app.club_id', true), '')::integer $$;

create or replace function platform_mode()
returns boolean
language sql
stable
as $$ select coalesce(current_setting('app.platform_mode', true), '') = 'true' $$;

